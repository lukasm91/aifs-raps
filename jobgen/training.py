"""Ordinary training-case definitions, kept together for easy review.

Special workloads (correctness and inference) remain explicit in the catalog
because their launch semantics differ from ordinary training cases.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal


@dataclass(frozen=True)
class TrainingCase:
    """Defaults for a conventional Anemoi training case."""

    selector: str
    id_profile: str
    benchmark: Literal["throughput", "highres"]
    nodes: int
    workers: int
    batch_limit: int
    max_epochs: int
    time_limit: str
    mapper_chunks: int
    processor_chunks: int
    ensembles: int = 1
    profiling: bool = False


# Keep the reference workload defaults together for review.
TRAINING_CASES: tuple[TrainingCase, ...] = (
    TrainingCase(
        selector="throughput", id_profile="throughput", benchmark="throughput",
        nodes=4, workers=4, batch_limit=900, max_epochs=2, time_limit="01:00:00",
        mapper_chunks=4, processor_chunks=4,
    ),
    TrainingCase(
        selector="highres", id_profile="highres", benchmark="highres",
        nodes=64, workers=4, batch_limit=180, max_epochs=2, time_limit="04:00:00",
        mapper_chunks=32, processor_chunks=8, ensembles=2,
    ),
)


def training_cases(selector: str) -> tuple[TrainingCase, ...]:
    """Return the conventional training cases generated by one CLI selector."""
    return tuple(case for case in TRAINING_CASES if case.selector == selector)


RUNDIR_REF = "${oc.env:RUNDIR}"
DEFAULT_COMPILE_MODULES = "[{module:torch.nn.Identity},{module:anemoi.models.layers.conv.GraphTransformerConv}]"


def throughput_args(
    *,
    nodes: int,
    batch_limit: int,
    max_epochs: int,
    num_workers: int,
    ntasks_per_node: int = 4,
    mapper_chunks: int = 16,
    processor_chunks: int = 8,
    pin_memory: bool = True,
    profile: bool = False,
    extra_args: tuple[str, ...] = (),
) -> tuple[str, tuple[str, ...]]:
    training_mode = "profile" if profile else "train"
    global_bs_per_ens = 16
    num_gpus = nodes * ntasks_per_node
    if num_gpus >= global_bs_per_ens:
        local_bs = 1
        num_gpus_per_model = num_gpus // global_bs_per_ens
    else:
        local_bs = global_bs_per_ens // num_gpus
        num_gpus_per_model = 1

    args = (
        training_mode,
        "--config-name=raps",
        f"model.processor.num_chunks={processor_chunks}",
        f"model.encoder.num_chunks={mapper_chunks}",
        f"model.decoder.num_chunks={mapper_chunks}",
        "model=graphtransformer",
        "~model.processor.window_size",
        "model.num_channels=1024",
        "hardware.files.dataset=aifs-benchmarking-o800-10years-cloned.zarr",
        "dataloader.training.end=20231230",
        "dataloader.validation.start=20231231",
        "dataloader.validation.end=20231231",
        f"dataloader.limit_batches.training={batch_limit}",
        f"hardware.num_gpus_per_model={num_gpus_per_model}",
        f"hardware.num_gpus_per_node={ntasks_per_node}",
        f"hardware.num_nodes={nodes}",
        "hardware.paths.data=/data/throughput",
        f"training.max_epochs={max_epochs}",
        f"dataloader.pin_memory={str(pin_memory).lower()}",
        f"dataloader.num_workers.training={num_workers}",
        f"dataloader.num_workers.validation={num_workers}",
        f"hardware.paths.output={RUNDIR_REF}/anemoi/",
        "data.resolution=o800",
        "training.rollout.start=1",
        "training.rollout.max=1",
        "graph.overwrite=false",
        "hardware.paths.graph=/graphs/",
        "hardware.files.graph=multi_scale.o800_0.6CoF_7_3NN_o800.graph",
        "graph=multi_scale",
        "graph.nodes.hidden.node_builder.resolution=7",
        "graph.edges.0.edge_builders.0.cutoff_factor=0.6",
        "graph.edges.2.edge_builders.0.num_nearest_neighbours=3",
        "graph.edges.1.edge_builders.0.scale_resolutions=7",
        "~graph.nodes.hidden.node_builder.grid",
        "hardware.accelerator=gpu",
        "training.precision=bf16-fp32-opt",
        "model.layer_kernels.QueryNorm._target_=torch.nn.LayerNorm",
        "model.layer_kernels.KeyNorm._target_=torch.nn.LayerNorm",
        f"model.compile={DEFAULT_COMPILE_MODULES}",
        f"hydra.run.dir={RUNDIR_REF}/hydra",
    )
    if local_bs > 1:
        args += (
            f"dataloader.batch_size.training={local_bs}",
            f"dataloader.batch_size.validation={local_bs}",
        )
    args += extra_args
    return args


def highres_args(
    *,
    nodes: int,
    ens_size: int,
    local_bs: int,
    batch_limit: int,
    max_epochs: int,
    num_workers: int,
    pin_memory: bool = True,
    ntasks_per_node: int = 4,
    global_bs_per_ens: int = 16,
    num_channels: int = 2048,
    mapper_chunks: int = 32,
    processor_chunks: int = 8,
    overwrite_graph: str = "false",
    graph_path: str = "/graphs/",
    attention_implementation: str | None = None,
    extra_args: tuple[str, ...] = (),
) -> tuple[str, tuple[str, ...]]:
    num_gpus = nodes * ntasks_per_node
    num_models_per_ens = global_bs_per_ens // local_bs
    required_multiple = ens_size * num_models_per_ens
    if num_gpus < required_multiple or num_gpus % required_multiple:
        raise ValueError(
            f"{num_gpus} GPUs cannot be divided evenly across {ens_size} ensembles "
            f"with {num_models_per_ens} models per ensemble"
        )
    num_gpus_per_model = num_gpus // required_multiple

    args = [
        "train",
        "--config-name=raps",
        f"model.processor.num_chunks={processor_chunks}",
        f"model.encoder.num_chunks={mapper_chunks}",
        f"model.decoder.num_chunks={mapper_chunks}",
        "model.processor.window_size=2160",
        f"model.num_channels={num_channels}",
        "hardware.files.dataset=aifs-benchmark-4km-2years-synthetic.zarr",
        "dataloader.training.end=20230929",
        "dataloader.validation.start=20230930",
        "dataloader.validation.end=20230930",
        f"dataloader.limit_batches.training={batch_limit}",
        f"hardware.num_gpus_per_model={num_gpus_per_model}",
        f"hardware.num_gpus_per_node={ntasks_per_node}",
        f"hardware.num_nodes={nodes}",
        "hardware.paths.data=/data/high-res",
        f"training.max_epochs={max_epochs}",
        f"dataloader.pin_memory={str(pin_memory).lower()}",
        f"graph.overwrite={overwrite_graph}",
    ]
    if ens_size > 1:
        args.extend(
            (
                "training=less_memory_loss_ensemble",
                "datamodule=ens",
                "model=transformer_ens",
                "hardware.files.truncation=null",
                "hardware.files.truncation_inv=null",
                f"+hardware.num_gpus_per_ensemble={ens_size * num_gpus_per_model}",
                "training.ensemble_size_per_device=1",
            )
        )
    args.extend(
        (
            f"dataloader.num_workers.training={num_workers}",
            f"dataloader.num_workers.validation={num_workers}",
            f"hardware.paths.output={RUNDIR_REF}/anemoi/",
            "data.resolution=o2560",
            "training.rollout.start=1",
            "training.rollout.max=1",
            f"hardware.paths.graph={graph_path}",
            "hardware.files.graph=encoder_decoder_only.o2560_0.6CoF_o256_3NN_o2560.graph",
            "graph=encoder_decoder_only",
            "graph.nodes.hidden.node_builder.grid=o256",
            "graph.edges.0.edge_builders.0.cutoff_factor=0.6",
            "graph.edges.1.edge_builders.0.num_nearest_neighbours=3",
            "hardware.accelerator=gpu",
            "training.precision=bf16-fp32-opt",
            "model.layer_kernels.QueryNorm._target_=torch.nn.LayerNorm",
            "model.layer_kernels.KeyNorm._target_=torch.nn.LayerNorm",
            f"model.compile={DEFAULT_COMPILE_MODULES}",
            "data=zarr_no_insolation",
            f"hydra.run.dir={RUNDIR_REF}/hydra",
        )
    )
    if attention_implementation:
        args.append(f"model.processor.attention_implementation={attention_implementation}")
    if local_bs > 1:
        args.extend(
            (
                f"dataloader.batch_size.training={local_bs}",
                f"dataloader.batch_size.validation={local_bs}",
            )
        )
    args.extend(extra_args)
    return tuple(args)


