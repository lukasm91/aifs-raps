#!/usr/bin/env python3
"""Generate a single-node job that expands a real dataset into a benchmark dataset."""

from __future__ import annotations

import argparse
import shlex
from pathlib import Path

from jobgen.cluster import load_json_object


REPO_DIR = Path(__file__).resolve().parent
DEFAULT_OUTPUT = REPO_DIR / "generated" / "dataset-expansion"


def positive_int(value: str) -> int:
    parsed = int(value)
    if parsed < 1:
        raise argparse.ArgumentTypeError("expected a positive integer")
    return parsed


def load_config(name_or_path: str) -> dict[str, object]:
    path = Path(name_or_path)
    if not path.suffix:
        path = REPO_DIR / "clusters" / f"{name_or_path}.json"
    path = path.expanduser().resolve()
    return load_json_object(
        path,
        missing_message="cluster config does not exist: {path}",
        object_message="cluster config must contain a JSON object",
    )


def required_string(config: dict[str, object], *keys: str) -> str:
    value: object = config
    for key in keys:
        if not isinstance(value, dict) or key not in value:
            raise SystemExit(f"cluster config must define {'.'.join(keys)}")
        value = value[key]
    if not isinstance(value, str) or not value:
        raise SystemExit(f"cluster config must define {'.'.join(keys)} as a non-empty string")
    return value


def required_int(config: dict[str, object], key: str) -> int:
    value = config.get(key)
    if not isinstance(value, int) or value < 1:
        raise SystemExit(f"cluster config must define {key} as a positive integer")
    return value


def render_job(
    *,
    dataset: str,
    source: Path,
    destination: Path,
    image: str,
    slurm: list[object],
    cpus: int,
    time_limit: str,
    workers: int,
    replace_dataset: bool,
    output: Path,
) -> str:
    if not source.is_absolute() or not destination.is_absolute():
        raise SystemExit("dataset expansion source and destination must be absolute paths")
    if source == destination or source in destination.parents or destination in source.parents:
        raise SystemExit("dataset expansion source and destination must be separate, non-nested paths")

    job_id = f"expand-{dataset}-dataset"
    preset_flag = f"--{dataset}"
    replace_flag = " --force" if replace_dataset else ""
    slurm_header = "\n".join(f"#SBATCH {item}" for item in slurm)
    relative_depth = len((output / "jobs").relative_to(REPO_DIR).parts)
    repo_suffix = "/".join(".." for _ in range(relative_depth))

    return f'''#!/bin/bash --login
# Generated by generate_dataset_expansion_jobs.py
#SBATCH --job-name={job_id}
#SBATCH --nodes=1
{slurm_header}
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --hint=nomultithread
#SBATCH --time={time_limit}
#SBATCH --output=logs/%x-%j.slurm.out

set -euo pipefail

script_source=${{BASH_SOURCE[0]}}
if [[ "$script_source" == /var/spool/slurm/* ]]; then
  candidate=${{SLURM_SUBMIT_DIR:?SLURM_SUBMIT_DIR is required for an sbatch job}}
  while [[ "$candidate" != / && ! -f "$candidate/generate_dataset_expansion_jobs.py" ]]; do
    candidate=$(dirname -- "$candidate")
  done
  script_dir=$candidate
else
  if [[ "$script_source" != /* ]]; then
    script_source="$PWD/$script_source"
  fi
  script_dir=$(cd -- "$(dirname -- "$script_source")/{repo_suffix}" && pwd -P)
fi
if [[ ! -f "$script_dir/generate_dataset_expansion_jobs.py" ]]; then
  echo "cannot locate direct launcher repository" >&2
  exit 2
fi

source_dataset={shlex.quote(str(source))}
destination_dataset={shlex.quote(str(destination))}
mkdir -p "$script_dir/logs" "$destination_dataset"

mounts="$script_dir:/work,$script_dir/docker/make_synthetic_benchmark_zarr.py:/opt/aifs-raps/bin/make_synthetic_benchmark_zarr.py:ro,$source_dataset:/input/source.zarr:ro,$destination_dataset:/output/destination.zarr"

set -x
srun --overlap --exact --nodes=1 -n 1 --ntasks-per-node=1 --cpus-per-task={cpus} \\
  --container-image={shlex.quote(image)} \\
  --container-mounts "$mounts" \\
  --container-workdir=/work \\
  python /opt/aifs-raps/bin/make_synthetic_benchmark_zarr.py \\
    {preset_flag} \\
    --source /input/source.zarr \\
    --workers {workers}{replace_flag} \\
    /output/destination.zarr
set +x
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, help="Cluster config name or JSON path.")
    parser.add_argument("--dataset", choices=("throughput", "highres"), required=True)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--time", default="00:45:00", help="Slurm time limit.")
    parser.add_argument("--workers", type=positive_int, default=16)
    parser.add_argument("--replace-dataset", action="store_true", help="Replace a populated destination dataset.")
    parser.add_argument("--force", action="store_true", help="Replace this generated launcher only.")
    args = parser.parse_args()

    config = load_config(args.config)
    expansion = config.get("dataset_expansion")
    entry = expansion.get(args.dataset) if isinstance(expansion, dict) else None
    if not isinstance(entry, dict):
        raise SystemExit(f"cluster config must define dataset_expansion.{args.dataset}")
    source = Path(required_string(config, "dataset_expansion", args.dataset, "source"))
    destination = Path(required_string(config, "dataset_expansion", args.dataset, "destination"))
    image = required_string(config, "container")
    slurm = config.get("slurm")
    if not isinstance(slurm, list):
        raise SystemExit("cluster config must define slurm as a list")

    output = args.output.resolve()
    try:
        output.relative_to(REPO_DIR)
    except ValueError as exc:
        raise SystemExit(f"--output must be inside {REPO_DIR}") from exc
    jobs = output / "jobs"
    jobs.mkdir(parents=True, exist_ok=True)
    (jobs / "logs").mkdir(exist_ok=True)
    path = jobs / f"expand-{args.dataset}-dataset.slurm"
    if path.exists() and not args.force:
        raise SystemExit(f"refusing to overwrite {path}; use --force")
    path.write_text(
        render_job(
            dataset=args.dataset,
            source=source,
            destination=destination,
            image=image,
            slurm=slurm,
            cpus=required_int(config, "cpus_per_task"),
            time_limit=args.time,
            workers=args.workers,
            replace_dataset=args.replace_dataset,
            output=output,
        )
    )
    path.chmod(0o755)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
